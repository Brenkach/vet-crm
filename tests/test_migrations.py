"""Міграції Alembic: застосовуються з нуля, відкочуються і повністю відповідають моделям."""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

ROOT = Path(__file__).resolve().parent.parent


@pytest.fixture
def alembic_config(tmp_path):
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("sqlalchemy.url", f"sqlite+aiosqlite:///{tmp_path / 'migrations.db'}")
    return cfg


def test_upgrade_and_downgrade(alembic_config):
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    command.upgrade(alembic_config, "head")


def test_migrations_match_models(alembic_config):
    # Якщо змінили моделі й забули створити міграцію — тест упаде
    command.upgrade(alembic_config, "head")
    try:
        command.check(alembic_config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"Моделі не збігаються з міграціями, створіть нову: alembic revision --autogenerate\n{exc}")
